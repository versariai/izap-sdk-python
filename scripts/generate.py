"""Regenerate the client in ``src/izap/_generated`` from the vendored public OpenAPI schema.

    uv run python scripts/generate.py           # regenerate from openapi/izap-public.json
    uv run python scripts/generate.py --check   # ...and fail if that changed the output on disk (CI)

``IZAP_OPENAPI_INPUT`` points it at another schema file. ``openapi/izap-public.json`` is a
vendored copy of iZap's public schema, so the SDK regenerates on its own once it is
mirrored out of the monorepo; ``scripts/sync_schema.py`` refreshes it. Besides
``_generated/`` the script writes the public re-export modules ``izap/api/<tag>.py`` and
``izap/models.py``, so the import paths users depend on survive a generator swap.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi" / "izap-public.json"
CONFIG = ROOT / "openapi-python-client.yaml"
PACKAGE = ROOT / "src" / "izap"
GENERATED = PACKAGE / "_generated"
PUBLIC_API = PACKAGE / "api"
PUBLIC_MODELS = PACKAGE / "models.py"
OUTPUTS = (GENERATED, PUBLIC_API, PUBLIC_MODELS)

HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
BUSINESS_ID_HEADER = "business-id"
HEADER = '"""{doc} Generated by scripts/generate.py; do not edit."""\n'


def venv_tool(name: str) -> str:
    tool = shutil.which(name, path=str(Path(sys.executable).parent))
    if tool is None:
        sys.exit(f"{name} is not installed in this environment; run `uv sync` first.")
    return tool


def python_name(parameter: str) -> str:
    return re.sub(r"\W", "_", parameter).lower()


def operations(schema: dict[str, Any]) -> list[tuple[str, str, dict[str, Any], dict[str, Any]]]:
    return [
        (method, path, item, operation)
        for path, item in schema.get("paths", {}).items()
        for method, operation in item.items()
        if method in HTTP_METHODS
    ]


def declare_missing_path_params(schema: dict[str, Any]) -> list[str]:
    """Declare path template variables that an operation leaves undeclared.

    The backend resolves ``business_id`` inside a dependency on some routes, so
    FastAPI never lists it under ``parameters``. OpenAPI requires every template
    variable to be declared and openapi-python-client skips operations that do not,
    so each missing one is added as a required string. The optional ``business-id``
    header those operations also declare is dropped: the path already selects the
    business, and keeping both would generate ``business_id_path``/``business_id_header``
    arguments. A no-op once the backend schema declares them.
    """
    patched: list[str] = []
    for method, path, item, operation in operations(schema):
        template = re.findall(r"{([^}]+)}", path)
        params = operation.get("parameters", [])
        declared = {p["name"] for p in [*item.get("parameters", []), *params] if p.get("in") == "path"}
        missing = [name for name in template if name not in declared]
        if not missing:
            continue
        by_name = {p["name"]: p for p in params if p.get("in") == "path"}
        for name in missing:
            by_name[name] = {"name": name, "in": "path", "required": True, "schema": {"type": "string"}}
        ordered = [by_name[name] for name in template if name in by_name]
        added = {python_name(name) for name in missing}
        rest = [p for p in params if p.get("in") != "path" and python_name(p["name"]) not in added]
        operation["parameters"] = ordered + rest
        patched.append(f"{method.upper()} {path}: {', '.join(missing)}")
    return patched


def normalise_business_header(schema: dict[str, Any]) -> int:
    """Generate the ``business-id`` header as an optional plain string.

    ``izap.Client(business_id=...)`` sends that header on every request, so a required
    per-call argument would make callers repeat it; a request that carries it neither way
    still gets the API's own 422. And the generator puts a ``format: uuid`` header into
    the request as a ``UUID`` object, which httpx rejects, so its schema becomes a string.
    """
    changed = 0
    for _method, _path, _item, operation in operations(schema):
        for param in operation.get("parameters", []):
            if param.get("in") == "header" and param.get("name", "").lower() == BUSINESS_ID_HEADER:
                param["required"] = False
                param["schema"] = {"type": "string"}
                changed += 1
    return changed


def drop_error_responses(schema: dict[str, Any]) -> int:
    """Generate success types only: the SDK raises ``IzapApiError`` for every 4xx/5xx.

    Left in, each documented error would widen every return type to a union the
    caller could never receive (``SendChatMessageOut | HTTPValidationError | None``).
    ``default`` is FastAPI's catch-all for an undocumented status and resolves to the
    same ``ApiError`` shape, so it is dropped alongside the numbered statuses.
    """
    dropped = 0
    for _method, _path, _item, operation in operations(schema):
        responses = operation.get("responses", {})
        for status in [s for s in responses if str(s)[:1] in ("4", "5") or str(s) == "default"]:
            del responses[status]
            dropped += 1
    return dropped


def string_list(values: list[str], indent: str = "    ") -> str:
    return "".join(f"{indent}{value},\n" for value in values)


def write_public_modules() -> None:
    if PUBLIC_API.exists():
        shutil.rmtree(PUBLIC_API)
    PUBLIC_API.mkdir()
    (PUBLIC_API / "__init__.py").write_text(HEADER.format(doc="Endpoint functions, one module per API tag."))
    for tag in sorted(p for p in (GENERATED / "api").iterdir() if p.is_dir() and not p.name.startswith("_")):
        endpoints = sorted(p.stem for p in tag.glob("*.py") if p.stem != "__init__")
        (PUBLIC_API / f"{tag.name}.py").write_text(
            HEADER.format(doc=f"``{tag.name}`` endpoints.")
            + f"\nfrom .._generated.api.{tag.name} import (\n{string_list(endpoints)})\n"
            + f"\n__all__ = [\n{string_list([json.dumps(e) for e in endpoints])}]\n"
        )

    models_init = ast.parse((GENERATED / "models" / "__init__.py").read_text())
    names: list[str] = []
    for node in models_init.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            names = sorted(ast.literal_eval(node.value))
    PUBLIC_MODELS.write_text(
        HEADER.format(doc="Request and response models.")
        + f"\nfrom ._generated.models import (\n{string_list(names)})\n"
        + f"\n__all__ = [\n{string_list([json.dumps(n) for n in names])}]\n"
    )


def generate(schema_path: Path) -> None:
    schema = json.loads(schema_path.read_text())
    for fix in declare_missing_path_params(schema):
        print(f"declared missing path parameter: {fix}", file=sys.stderr)
    print(f"normalised the business-id header on {normalise_business_header(schema)} operations", file=sys.stderr)
    print(f"dropped {drop_error_responses(schema)} documented error responses", file=sys.stderr)

    with tempfile.TemporaryDirectory() as tmp:
        input_path = Path(tmp) / "openapi.json"
        input_path.write_text(json.dumps(schema))
        result = subprocess.run(  # noqa: S603 - fixed argv, the venv's own generator
            [
                venv_tool("openapi-python-client"),
                "generate",
                "--path",
                str(input_path),
                "--output-path",
                str(GENERATED),
                "--meta",
                "none",
                "--overwrite",
                "--config",
                str(CONFIG),
            ],
            capture_output=True,
            text=True,
            check=False,
        )
    if result.returncode != 0 or "will not be generated" in result.stdout + result.stderr:
        sys.exit(f"openapi-python-client failed or skipped part of the schema:\n{result.stdout}{result.stderr}")

    write_public_modules()

    targets = [str(p) for p in OUTPUTS]
    ruff = venv_tool("ruff")
    subprocess.run([ruff, "check", "--fix-only", "--select", "I,F401", "--quiet", *targets], check=True)  # noqa: S603
    subprocess.run([ruff, "format", "--quiet", *targets], check=True)  # noqa: S603


def fingerprint() -> dict[str, str]:
    """Content hash of every generated file, so the drift check needs no git checkout."""
    files = (path for output in OUTPUTS for path in ([output] if output.is_file() else sorted(output.rglob("*"))))
    return {
        str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in files
        if path.is_file() and "__pycache__" not in path.parts
    }


def report_drift(before: dict[str, str], after: dict[str, str]) -> bool:
    changed = sorted(path for path in before.keys() | after.keys() if before.get(path) != after.get(path))
    if changed:
        print(
            "The committed client does not match what the schema generates. Run\n"
            "`uv run python scripts/generate.py` and commit the result. Changed:\n"
            + "\n".join(f"  {path}" for path in changed),
            file=sys.stderr,
        )
        return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if regenerating changes the output on disk")
    args = parser.parse_args()

    schema_path = Path(os.environ.get("IZAP_OPENAPI_INPUT") or SNAPSHOT)
    if not schema_path.is_file():
        sys.exit(f"schema not found: {schema_path}")
    before = fingerprint()
    generate(schema_path)
    return 0 if not args.check or report_drift(before, fingerprint()) else 1


if __name__ == "__main__":
    sys.exit(main())
